// Generates internal/web/static/icons.js from Gravity UI icons (@gravity-ui/icons, MIT), the set HeroUI uses inside its
// components, so the application's own icons match the ones the components draw.
// Usage: node ui/icons.mjs <node_modules directory>
import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const here=dirname(fileURLToPath(import.meta.url));
const modules=resolve(process.argv[2] || resolve(here,'node_modules'));
const pkg=resolve(modules,'@gravity-ui/icons');
const version=JSON.parse(await readFile(resolve(pkg,'package.json'),'utf8')).version;
if(version!=='2.23.0')throw Error(`@gravity-ui/icons: expected 2.23.0, got ${version}`);

// Application name -> Gravity UI icon.
const MAP={
 plus:'plus', settings:'gear', send:'arrow-up', folder:'folder', folderOpen:'folder-open', branch:'code-fork', check:'check', x:'xmark',
 alert:'triangle-exclamation', info:'circle-info', chevron:'chevron-right', chevDown:'chevron-down', chevUp:'chevron-up',
 panelRight:'layout-side-content-right', panelLeft:'layout-side-content-left', file:'file', fileText:'file-text', fileCode:'file-code',
 trash:'trash-bin', download:'arrow-down-to-line', upload:'arrow-up-from-line', commit:'code-commit-horizontal', external:'arrow-up-right-from-square',
 sparkles:'sparkles', layers:'layers', play:'play', shield:'shield', terminal:'terminal', refresh:'arrows-rotate-right',
 logout:'arrow-right-from-square', user:'person', link:'link', menu:'bars', stop:'stop', clock:'clock', code:'code', box:'cube',
 copy:'copy', history:'clock-arrow-rotate-left', diff:'code-compare', eye:'eye', edit:'pencil', globe:'globe', gauge:'speedometer',
 leaf:'circle-dollar', zap:'thunderbolt', server:'server', activity:'pulse', sun:'sun', moon:'moon', monitor:'display', more:'ellipsis',
 queue:'bars-play', list:'list-ul', search:'magnifier', compose:'pencil-to-square', grid:'layout-cells-large', chat:'comment',
 lock:'lock', pullRequest:'code-pull-request', agents:'persons', paperclip:'paperclip', inspect:'sliders', database:'database',
 checkCircle:'circle-check', xCircle:'circle-xmark', archive:'archive', tree:'folder-tree',
};

const out=[];
for(const [name,file] of Object.entries(MAP)){
 const svg=await readFile(resolve(pkg,'svgs',file+'.svg'),'utf8');
 if(!/viewBox="0 0 16 16"/.test(svg))throw Error(`${file}: not a 16x16 icon`);
 let body=svg.replace(/^<svg[^>]*>/,'').replace(/<\/svg>\s*$/,'');
 // A clip path covering the whole 16x16 view clips nothing.
 const clip=body.match(/^<g clip-path="url\(#(\w+)\)">([\s\S]*)<\/g><defs><clipPath id="\1"><path fill="currentColor" d="M0 0h16v16H0z"\/><\/clipPath><\/defs>$/);
 if(clip)body=clip[2];
 // A single <g fill="currentColor"> wrapper is the same as filling each path.
 const group=body.match(/^<g( fill="currentColor")?( fill-rule="evenodd")?( clip-rule="evenodd")?>([\s\S]*)<\/g>$/);
 if(group)body=group[4];
 const paths=[...body.matchAll(/<path([^>]*)\/>/g)];
 if(body.replace(/<path[^>]*\/>/g,'').trim())throw Error(`${file}: elements other than <path>`);
 const rules=new Set(paths.map(([,attrs])=>/fill-rule="evenodd"/.test(attrs)||group?.[2]?'evenodd':'nonzero'));
 // All of one icon's paths share one fill rule, so they can be drawn as one path.
 if(rules.size!==1)throw Error(`${file}: mixed fill rules`);
 const d=paths.map(([,attrs])=>attrs.match(/ d="([^"]+)"/)[1]).join('');
 out.push(`  ${name}: ${JSON.stringify(rules.has('evenodd')?d:'nonzero:'+d)},`);
}
const license=(await readFile(resolve(pkg,'LICENSE'),'utf8')).trim().split('\n').map(line=>(' * '+line).trimEnd()).join('\n');
await writeFile(resolve(here,'../internal/web/static/icons.js'),
`// Generated by ui/icons.mjs from @gravity-ui/icons ${version}; do not edit by hand.
/*
${license}
 */
// Each value is one path on a 16x16 grid, filled with currentColor; "nonzero:" marks the few drawn with the nonzero fill rule.
export const ICONS = {
${out.join('\n')}
};

// iconPath splits a value into its path data and fill rule.
export function iconPath(value) {
  const nonzero = typeof value === "string" && value.startsWith("nonzero:");
  return { d: nonzero ? value.slice(8) : value || "", rule: nonzero ? "nonzero" : "evenodd" };
}
`);
console.log(`Wrote ${out.length} icons`);
